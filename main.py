"""Entry point for the make.fun competition.

This script validates the front‑page image `entry.png` that is committed in the
repository (it is generated by a separate build‑time script) and copies it to
the grader's output directory.  It checks the PNG signature, the IHDR chunk,
image dimensions, file size, and ensures the copy is byte‑perfect.  On success
it prints the destination path, dimensions, size and SHA‑256 digest.
"""

import os
import sys
import struct
import hashlib
from pathlib import Path


PNG_SIGNATURE = b'\x89PNG\r\n\x1a\n'
MAX_FILE_SIZE = 1_048_576  # 1 MiB
MAX_DIMENSION = 1024
IHDR_TYPE = b'IHDR'


def read_png_dimensions(p: Path) -> tuple[int, int]:
    """
    Read the first 33 bytes of a PNG file, verify the signature and IHDR chunk,
    and return (width, height) as unsigned 32‑bit big‑endian integers.

    Raises:
        ValueError: if the file is not a valid PNG or the IHDR chunk is missing.
    """
    try:
        data = p.read_bytes()[:33]
    except OSError as e:
        raise ValueError(f"cannot read file: {e}")

    if len(data) < 33:
        raise ValueError("file too short to contain required PNG header")

    if data[:8] != PNG_SIGNATURE:
        raise ValueError("invalid PNG signature")

    # Length (4 bytes) + Chunk type (4 bytes) start at offset 8
    if data[12:16] != IHDR_TYPE:
        raise ValueError("IHDR chunk not found where expected")

    # Width and height are the first 8 bytes of the IHDR data (offset 16)
    width = struct.unpack(">I", data[16:20])[0]
    height = struct.unpack(">I", data[20:24])[0]
    return width, height


def compute_sha256(data: bytes) -> str:
    """Return the hex SHA‑256 digest of the given bytes."""
    return hashlib.sha256(data).hexdigest()


def error(msg: str) -> None:
    """Print an error message to stderr and exit with status 1."""
    print(f"Error: {msg}", file=sys.stderr)
    sys.exit(1)


def main() -> None:
    # Locate source file
    src_path = Path(__file__).with_name("entry.png")
    if not src_path.is_file():
        error("entry.png is missing")

    # File size check
    try:
        size = src_path.stat().st_size
    except OSError as e:
        error(f"cannot stat entry.png: {e}")
    if size > MAX_FILE_SIZE:
        error("entry.png exceeds maximum allowed size of 1 048 576 bytes")

    # Validate PNG and obtain dimensions
    try:
        src_width, src_height = read_png_dimensions(src_path)
    except ValueError as e:
        error(f"invalid PNG file: {e}")

    if src_width > MAX_DIMENSION or src_height > MAX_DIMENSION:
        error("image dimensions exceed the 1024 px limit")

    if (src_width, src_height) != (MAX_DIMENSION, MAX_DIMENSION):
        error("image must be exactly 1024x1024")

    # Determine output directory
    out_dir_str = os.getenv("MAKEFUN_OUTPUT_DIR", "/output")
    out_dir = Path(out_dir_str)
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
    except OSError as e:
        error(f"cannot create output directory '{out_dir}': {e}")

    dest_path = out_dir / "entry.png"

    # Copy file
    try:
        data = src_path.read_bytes()
        dest_path.write_bytes(data)
    except OSError as e:
        error(f"file copy failed: {e}")

    # Verify copy integrity
    try:
        copied_data = dest_path.read_bytes()
    except OSError as e:
        error(f"cannot read copied file: {e}")

    if data != copied_data:
        error("copied file differs from source")

    if len(data) < 12 or data[-12:-8] != b"\x00\x00\x00\x00" or data[-8:-4] != b"IEND":
        error("PNG file is truncated: IEND chunk missing")

    # Verify dimensions of the copied file
    try:
        dst_width, dst_height = read_png_dimensions(dest_path)
    except ValueError as e:
        error(f"copied file is not a valid PNG: {e}")

    if (dst_width, dst_height) != (src_width, src_height):
        error("dimensions of copied file differ from source")

    # Compute SHA‑256 digest
    digest = compute_sha256(data)

    # Success output
    print(f"{dest_path} {src_width}x{src_height} {size} {digest}")
    sys.exit(0)


if __name__ == "__main__":
    main()
